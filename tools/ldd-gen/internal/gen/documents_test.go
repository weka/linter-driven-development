package gen_test

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/weka/linter-driven-development/tools/ldd-gen/internal/gen"
)

const (
	digestProfile  = "handbook: coding-rules/p.md\ndigest: coding-rules/p.digest.md\n"
	digestTemplate = "<!-- Generated by tools/ldd-gen -->\n# {{.Lang}} digest of {{handbookPath}}\n{{include \"handbook/notes.md\"}}\n"
)

func digestRepo(t *testing.T) string {
	t.Helper()
	root := handbookRepo(t)
	write(t, root, "lang/p/profile.yaml", profileYAML+digestProfile)
	write(t, root, "core/handbook/coding-rules.digest.md", digestTemplate)
	return root
}

func TestDigest_GenerateThenCheck(t *testing.T) {
	t.Parallel()
	root := digestRepo(t)
	repo, err := gen.Open(root)
	require.NoError(t, err)

	var out bytes.Buffer
	n, err := repo.Check(&out)
	require.NoError(t, err)
	assert.Equal(t, 5, n, "three plugin files, the handbook and the digest are missing")
	assert.Contains(t, out.String(), "missing       coding-rules/p.digest.md")

	require.NoError(t, repo.Generate("p"))
	got, err := os.ReadFile(filepath.Join(root, "coding-rules/p.digest.md"))
	require.NoError(t, err)
	assert.Equal(t, "<!-- Generated by tools/ldd-gen -->\n# Lang digest of p.md\nnotes\n", string(got))
	assert.NoFileExists(t, filepath.Join(root, "out-plugin/handbook/coding-rules.digest.md"), "the template is not a plugin file")

	out.Reset()
	n, err = repo.Check(&out)
	require.NoError(t, err)
	assert.Zero(t, n, out.String())

	write(t, root, "core/handbook/coding-rules.digest.md", digestTemplate+"more\n")
	out.Reset()
	n, err = repo.Check(&out)
	require.NoError(t, err)
	assert.Equal(t, 1, n, "only the digest changed")
	assert.Contains(t, out.String(), "changed       coding-rules/p.digest.md")

	require.NoError(t, repo.Generate("p"))
	require.NoError(t, os.Chmod(filepath.Join(root, "coding-rules/p.digest.md"), 0o755))
	out.Reset()
	n, err = repo.Check(&out)
	require.NoError(t, err)
	assert.Equal(t, 1, n)
	assert.Contains(t, out.String(), "exec-changed  coding-rules/p.digest.md")
}

func TestDigest_GoResidueFailsANonGoDigest(t *testing.T) {
	t.Parallel()
	root := digestRepo(t)
	write(t, root, "core/handbook/coding-rules.digest.md", digestTemplate+"start a goroutine\n")
	repo, err := gen.Open(root)
	require.NoError(t, err)
	_, _, err = repo.Render("p")
	require.ErrorContains(t, err, "coding-rules/p.digest.md carries Go residue")
	assert.Contains(t, err.Error(), "[goroutine]")
}

func TestDigest_RefusesToOverwriteAHandWrittenFile(t *testing.T) {
	t.Parallel()
	root := digestRepo(t)
	write(t, root, "coding-rules/p.digest.md", "# my own digest\n")
	repo, err := gen.Open(root)
	require.NoError(t, err)
	err = repo.Generate("p")
	require.ErrorContains(t, err, "coding-rules/p.digest.md exists and is not a generated handbook or digest")
	got, err := os.ReadFile(filepath.Join(root, "coding-rules/p.digest.md"))
	require.NoError(t, err)
	assert.Equal(t, "# my own digest\n", string(got), "nothing was overwritten")
	assert.NoFileExists(t, filepath.Join(root, "coding-rules/p.md"), "the refusal runs before any document is written")
	assert.NoFileExists(t, filepath.Join(root, "out-plugin/rules/R1.md"), "the refusal runs before the plugin directory is written")
}

func TestDigest_PathConflicts(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name      string
		documents string
		want      string
	}{
		{name: "digest inside a plugin directory", documents: "handbook: coding-rules/q.md\ndigest: out-plugin/DIGEST.md\n", want: "inside a directory the generator owns"},
		{name: "digest inside lang", documents: "handbook: coding-rules/q.md\ndigest: lang/q.digest.md\n", want: "inside a directory the generator owns"},
		{name: "digest at another binding's handbook", documents: "handbook: coding-rules/q.md\ndigest: coding-rules/p.md\n", want: "both render"},
		{name: "handbook at another binding's digest", documents: "handbook: coding-rules/p.digest.md\n", want: "both render"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := digestRepo(t)
			write(t, root, "lang/q/profile.yaml", strings.Replace(profileYAML, "plugin: out-plugin", "plugin: q-plugin", 1)+tc.documents)
			repo, err := gen.Open(root)
			require.NoError(t, err)
			require.ErrorContains(t, repo.Generate("p"), tc.want)
			_, err = repo.Check(&bytes.Buffer{})
			require.ErrorContains(t, err, tc.want)
		})
	}
}
