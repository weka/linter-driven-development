package render_test

import (
	"strings"
	"testing"
	"testing/fstest"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/weka/linter-driven-development/tools/ldd-gen/internal/binding"
	"github.com/weka/linter-driven-development/tools/ldd-gen/internal/render"
)

const digest = `<!-- Generated by tools/ldd-gen -->
# {{.Lang}} digest, see {{handbookPath}}
- {{maximName "Tell, don't ask"}}
**Moves:** {{moves "rules/R1.md"}}
**Ask:** {{questions "rules/R1/questions.md" 2}}
`

func digestLang(t *testing.T, documents string) binding.Binding {
	t.Helper()
	return lang(t, fstest.MapFS{"profile.yaml": {Data: []byte(profileYAML + documents)}})
}

func digestCore(template string) fstest.MapFS {
	core := handbookCore()
	core["handbook/coding-rules.digest.md"] = &fstest.MapFile{Data: []byte(template)}
	return core
}

func TestDigest(t *testing.T) {
	t.Parallel()
	b := digestLang(t, "handbook: coding-rules/p.md\ndigest: coding-rules/digests/p.md\n")
	out, err := render.Digest(digestCore(digest), b)
	require.NoError(t, err)
	want := `<!-- Generated by tools/ldd-gen -->
# Lang digest, see ../p.md
- **Tell, don't ask.**
**Moves:** Replace Primitive with Domain Type · Extract Collection Type
**Ask:** Is the same predicate enforced in more than one place?
`
	assert.Equal(t, want, string(out))
}

func TestDigest_HandbookPathIsALinkDestination(t *testing.T) {
	t.Parallel()
	b := digestLang(t, "handbook: 'coding-rules/c#/my rules.md'\ndigest: coding-rules/c.digest.md\n")
	out, err := render.Digest(digestCore("<!-- Generated by tools/ldd-gen -->\n[the full handbook]({{handbookPath}})\n"), b)
	require.NoError(t, err)
	assert.Contains(t, string(out), "[the full handbook](c%23/my%20rules.md)")
}

func TestDigest_Errors(t *testing.T) {
	t.Parallel()
	documents := "handbook: coding-rules/p.md\ndigest: coding-rules/p.digest.md\n"
	cases := []struct {
		name      string
		template  string
		documents string
		want      string
	}{
		{name: "missing marker", template: "# no marker\n", documents: documents, want: "must begin with"},
		{name: "unknown maxim", template: "<!-- Generated by tools/ldd-gen -->\n{{maximName \"Nope\"}}\n", documents: documents, want: `maximName "Nope"`},
		{name: "no digest in the profile", template: "<!-- Generated by tools/ldd-gen -->\n{{handbookPath}}\n", documents: "", want: "names no handbook or no digest"},
		{name: "over the ceiling", template: "<!-- Generated by tools/ldd-gen -->\n" + strings.Repeat("x", render.DigestMaxBytes), documents: documents, want: "over the ceiling of 8000"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			_, err := render.Digest(digestCore(tc.template), digestLang(t, tc.documents))
			require.ErrorContains(t, err, tc.want)
		})
	}
}

func TestDigest_AtTheCeilingRenders(t *testing.T) {
	t.Parallel()
	marker := "<!-- Generated by tools/ldd-gen -->\n"
	template := marker + strings.Repeat("x", render.DigestMaxBytes-len(marker))
	out, err := render.Digest(digestCore(template), digestLang(t, ""))
	require.NoError(t, err)
	assert.Len(t, out, render.DigestMaxBytes)
}

func TestDigest_StaysOutOfThePluginTree(t *testing.T) {
	t.Parallel()
	tree, err := render.Render(digestCore(digest), lang(t, nil))
	require.NoError(t, err)
	assert.NotContains(t, tree, "handbook/coding-rules.digest.md", "the digest template is never a plugin file")
}
